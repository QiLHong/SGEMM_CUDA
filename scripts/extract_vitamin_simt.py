"""Extract exactly five upstream SIMT device functions; verify before compiling.

No PyTorch dependencies. Never modifies the reference repository.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

COMMIT = "520f97093a2abc239977be83d244b327d0e2e2ef"
NAMES = ["sgemm_tiling", "sgemm_at_tiling", "sgemm_at_bcf_swizzling",
         "sgemm_at_bcf_swizzling_rw", "sgemm_at_bcf_swizzling_dbf_rw"]


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vitamin", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    commit = subprocess.check_output(
        ["git", "-C", str(args.vitamin), "rev-parse", "HEAD"], text=True).strip()
    if commit != COMMIT:
        raise SystemExit(f"Reference commit differs: {commit}; refusing automatic update")
    relative = "kernels/sgemm/sgemm.cu"
    source = (args.vitamin / relative).read_text(encoding="utf-8")
    pack = (args.vitamin / "kernels/common/pack.cuh").read_text(encoding="utf-8")
    # Each function ends before the next template / torch-only binding section.
    start = source.index("// a block calculate c[128][128]")
    end = source.index("#define CHECK_T")
    body = source[start:end].rstrip() + "\n"
    names = re.findall(r"__global__ void (\w+)_kernel", body)
    assert names == NAMES, names
    float4 = next(line for line in pack.splitlines() if line.startswith("#define FLOAT4("))
    warp = next(line for line in pack.splitlines() if line.startswith("const int WARP_SIZE"))
    swizzle = next(line for line in source.splitlines() if line.startswith("#define SWIZZLE_A("))
    header = (
        "// Native extraction: vitamin-cuda, Copyright (c) 2025 wingedge; MIT.\n"
        "// https://github.com/QiLHong/vitamin-cuda/tree/" + COMMIT + "\n"
        "// Source: kernels/sgemm/sgemm.cu; see vitamin-LICENSE and provenance.json.\n"
        "// Generated by scripts/extract_vitamin_simt.py; device body unchanged.\n"
        "#pragma once\n#include <cuda_runtime.h>\n"
        + float4 + "\n" + swizzle + "\nnamespace vitamin_cuda {\n"
        + warp + "\n// BEGIN EXACT UPSTREAM DEVICE REGION\n"
        + body + "// END EXACT UPSTREAM DEVICE REGION\n"
        "} // namespace vitamin_cuda\n#undef FLOAT4\n#undef SWIZZLE_A\n"
    )
    if args.verify:
        assert args.output.read_text(encoding="utf-8") == header, "Extracted header differs"
    else:
        if args.output.exists():
            raise SystemExit("Refusing to overwrite existing extraction; use --verify")
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(header, encoding="utf-8", newline="\n")
        (args.output.parent / "vitamin-LICENSE").write_bytes(
            (args.vitamin / "LICENSE").read_bytes())
    manifest = {
        "reference_commit": commit, "repository": "https://github.com/QiLHong/vitamin-cuda",
        "source_path": relative, "functions": names,
        "source_start_line": source[:start].count("\n") + 1,
        "source_end_line": source[:end].count("\n"),
        "source_normalized_sha256": sha(source), "device_region_sha256": sha(body),
        "header_normalized_sha256": sha(header),
        "device_code_equal": True,
        "exceptions": [
            "LF normalization for byte comparison; no device-body edits",
            "Remove unrelated naive kernel and all torch binding functions/includes",
            "Replace pack.cuh by exactly its FLOAT4 macro and WARP_SIZE declaration",
            "Keep SWIZZLE_A macro; add vitamin_cuda namespace; undef local macros",
            "CUDA runtime include only; original license copied alongside",
            "Native launch wrappers enforce safe square shapes; no kernel algorithm edits"],
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                             encoding="utf-8")
    print(json.dumps(manifest, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
